"""Single reason registry with explicit scope and profile impact."""

from enum import StrEnum


class ReasonCode(StrEnum):
    MISSING_CAPTURE = "MISSING_CAPTURE"
    PARTIAL_CAPTURE = "PARTIAL_CAPTURE"
    RAW_HASH_MISMATCH = "RAW_HASH_MISMATCH"
    SOURCE_SCHEMA_INVALID = "SOURCE_SCHEMA_INVALID"
    SOURCE_NOT_READY = "SOURCE_NOT_READY"
    FREEFLOW_MISSING = "FREEFLOW_MISSING"
    SPEED_INVALID = "SPEED_INVALID"
    CLOSED = "CLOSED"
    CLOSURE_UNKNOWN = "CLOSURE_UNKNOWN"
    DIRECTION_UNVERIFIED = "DIRECTION_UNVERIFIED"
    DIRECTION_CONFLICT = "DIRECTION_CONFLICT"
    PATH_AMBIGUOUS = "PATH_AMBIGUOUS"
    PAIRED_COVERAGE_LOW = "PAIRED_COVERAGE_LOW"
    TRAFFIC_TIME_MISALIGNED = "TRAFFIC_TIME_MISALIGNED"
    SOURCE_VERSION_CONFLICT = "SOURCE_VERSION_CONFLICT"
    ABOVE_FREEFLOW = "ABOVE_FREEFLOW"
    WEATHER_MISSING = "WEATHER_MISSING"
    WEATHER_STALE = "WEATHER_STALE"
    WEATHER_GRID_FAR = "WEATHER_GRID_FAR"
    WEATHER_CODE_UNSUPPORTED = "WEATHER_CODE_UNSUPPORTED"
    LANES_MISSING = "LANES_MISSING"
    COVARIATE_CONFLICT = "COVARIATE_CONFLICT"
    DECODE_FAILED = "DECODE_FAILED"
    REFERENCE_TYPE_UNSUPPORTED = "REFERENCE_TYPE_UNSUPPORTED"
    FOOTPRINT_UNCALIBRATED = "FOOTPRINT_UNCALIBRATED"
    GEOMETRY_UNCERTAIN = "GEOMETRY_UNCERTAIN"
    OVERLAP_CONFLICT = "OVERLAP_CONFLICT"
    LEGAL_UNKNOWN = "LEGAL_UNKNOWN"
    REFERENCE_INCOMPLETE = "REFERENCE_INCOMPLETE"
    LENGTH_OUT_OF_POLICY = "LENGTH_OUT_OF_POLICY"
    NAME_COVERAGE_LOW = "NAME_COVERAGE_LOW"
    GEOMETRY_SELF_INTERSECTION = "GEOMETRY_SELF_INTERSECTION"
    COMPLEX_JUNCTION = "COMPLEX_JUNCTION"
    CONSTRUCTION = "CONSTRUCTION"
    PARALLEL_REVIEW_REQUIRED = "PARALLEL_REVIEW_REQUIRED"
    SHORTLIST_OVERLAP = "SHORTLIST_OVERLAP"
    OPENLR_MISSING = "OPENLR_MISSING"
    REPLAY_BUDGET_NOT_EVALUATED = "REPLAY_BUDGET_NOT_EVALUATED"
    RELATIVE_SPEED_INVALID = "RELATIVE_SPEED_INVALID"
    RELATIVE_SPEED_MISSING = "RELATIVE_SPEED_MISSING"
    TARGET_COVERAGE_LOW = "TARGET_COVERAGE_LOW"
    SOURCE_DIRECTION_METHOD_UNAPPROVED = "SOURCE_DIRECTION_METHOD_UNAPPROVED"
    ASSOCIATION_EVIDENCE_MISMATCH = "ASSOCIATION_EVIDENCE_MISMATCH"
    EVIDENCE_INVALID = "EVIDENCE_INVALID"
    DECODER_PROFILE_DISAGREEMENT = "DECODER_PROFILE_DISAGREEMENT"


CONTEXT = {ReasonCode.PARTIAL_CAPTURE}
COVARIATE = {r for r in ReasonCode if r.name.startswith("WEATHER_")} | {
    ReasonCode.LANES_MISSING,
    ReasonCode.COVARIATE_CONFLICT,
}
CANDIDATE = {
    ReasonCode.LENGTH_OUT_OF_POLICY,
    ReasonCode.NAME_COVERAGE_LOW,
    ReasonCode.GEOMETRY_SELF_INTERSECTION,
    ReasonCode.COMPLEX_JUNCTION,
    ReasonCode.CONSTRUCTION,
    ReasonCode.PARALLEL_REVIEW_REQUIRED,
    ReasonCode.SHORTLIST_OVERLAP,
}


def reason_metadata(reason: ReasonCode) -> dict:
    """Return scope, severity and blockers, separate from observation membership."""
    context = reason in CONTEXT
    covariate = reason in COVARIATE
    candidate = reason in CANDIDATE
    return {
        "scope": "capture"
        if context
        else "candidate"
        if candidate
        else "covariate"
        if covariate
        else "target",
        "severity": "warning" if context else "blocker",
        "blocks_ci": not (context or covariate or candidate),
        "blocks_model": not (context or candidate),
    }
